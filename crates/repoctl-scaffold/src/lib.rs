/// Built-in and local filesystem template resolver.
#[derive(Clone, Debug, Default)]
pub struct DefaultTemplateSourceResolver {
    parser: YamlManifestParser,
}

impl TemplateSourceResolver for DefaultTemplateSourceResolver {
    fn resolve(
        &self,
        root: &RepoRoot,
        source: &TemplateSource,
    ) -> Result<ResolvedTemplateSource, RepoctlError> {
        match source {
            TemplateSource::Builtin { name } => {
                let manifest = self.parser.parse_template_bytes(
                    format!("builtin:{name}/template.yaml"),
                    builtin_template_manifest(name)?.as_bytes(),
                )?;
                Ok(ResolvedTemplateSource {
                    root: RepoRelativePath::new(format!("templates/builtin/{name}"))
                        .map_err(RepoctlError::diagnostic)?,
                    manifest,
                })
            }
            TemplateSource::Local {
                root: template_root,
            } => {
                let manifest_path = RepoRelativePath::new(format!("{template_root}/template.yaml"))
                    .map_err(RepoctlError::diagnostic)?;
                let absolute = root.absolute.join(manifest_path.as_str());
                let bytes = fs::read(absolute.as_std_path())
                    .map_err(|source| RepoctlError::io(absolute.clone(), source))?;
                if let Some(schema) = template_schema(&bytes)
                    && schema != "repoctl.template/v1"
                {
                    return Err(RepoctlError::diagnostic(
                        Diagnostic::error(
                            "template.schema.unsupported",
                            format!("template schema `{schema}` is not renderable by repoctl"),
                        )
                        .with_path(manifest_path.as_str())
                        .with_help(
                            "use a repoctl.template/v1 template or the owning generator for this \
                             template schema",
                        ),
                    ));
                }
                let manifest = self
                    .parser
                    .parse_template_bytes(manifest_path.as_str(), &bytes)?;
                Ok(ResolvedTemplateSource {
                    root: template_root.clone(),
                    manifest,
                })
            }
        }
    }
}

fn template_schema(bytes: &[u8]) -> Option<String> {
    let text = std::str::from_utf8(bytes).ok()?;
    text.lines().find_map(|line| {
        let trimmed = line.trim();
        let value = trimmed.strip_prefix("schema:")?.trim();
        Some(value.trim_matches('"').trim_matches('\'').to_string())
    })
}

/// MiniJinja-backed template engine.
#[derive(Clone, Debug, Default)]
pub struct MiniJinjaTemplateEngine;

impl MiniJinjaTemplateEngine {
    /// Renders a UTF-8 template string with `MiniJinja`.
    pub fn render_str(
        &self,
        name: &str,
        source: &str,
        context: &serde_json::Value,
    ) -> Result<String, RepoctlError> {
        let mut environment = Environment::new();
        environment
            .add_template_owned(name.to_string(), source.to_string())
            .map_err(|error| {
                RepoctlError::diagnostic(Diagnostic::error(
                    "template.invalid",
                    format!("template `{name}` is invalid: {error}"),
                ))
            })?;
        let template = environment.get_template(name).map_err(|error| {
            RepoctlError::diagnostic(Diagnostic::error(
                "template.invalid",
                format!("template `{name}` is invalid: {error}"),
            ))
        })?;
        template.render(context).map_err(|error| {
            RepoctlError::diagnostic(Diagnostic::error(
                "template.render_failed",
                format!("template `{name}` render failed: {error}"),
            ))
        })
    }

    /// Renders source content according to the template file mode.
    pub fn render_content(
        &self,
        file: &repoctl_core::TemplateFile,
        source_content: &str,
        existing_content: Option<&str>,
        context: &serde_json::Value,
    ) -> Result<String, RepoctlError> {
        match file.mode.as_str() {
            "copy" => Ok(source_content.to_string()),
            "managed" => self.render_str(file.source.as_str(), source_content, context),
            "block" => {
                let rendered = self.render_str(file.source.as_str(), source_content, context)?;
                let block = render_block(&rendered);
                Ok(existing_content.map_or(block.clone(), |current| {
                    replace_or_append_block(current, &block)
                }))
            }
            mode => Err(RepoctlError::diagnostic(Diagnostic::error(
                "template.mode.unsupported",
                format!("unsupported template render mode `{mode}`"),
            ))),
        }
    }
}

impl TemplateEngine for MiniJinjaTemplateEngine {
    fn render(&self, request: &RenderRequest) -> Result<RenderedTemplate, RepoctlError> {
        let rendered = self.render_str("target", &request.file.target, &request.context)?;
        Ok(RenderedTemplate {
            bytes: rendered.into_bytes(),
        })
    }
}

fn root_path(path: &Path) -> Result<Utf8PathBuf, RepoctlError> {
    utf8_path_buf(path.to_path_buf()).map_err(RepoctlError::diagnostic)
}

fn locate_or_current(repo: Option<&Path>) -> Result<Utf8PathBuf, RepoctlError> {
    match repo {
        Some(path) => root_path(path),
        None => std::env::current_dir()
            .map_err(|source| RepoctlError::io(".", source))
            .and_then(|path| utf8_path_buf(path).map_err(RepoctlError::diagnostic)),
    }
}

fn directory_operation(path: &str) -> Result<FileOperation, RepoctlError> {
    Ok(FileOperation {
        path: RepoRelativePath::new(path.to_string()).map_err(RepoctlError::diagnostic)?,
        operation: "directory".to_string(),
        content: None,
    })
}

fn file_operation(path: &str, content: String) -> Result<FileOperation, RepoctlError> {
    Ok(FileOperation {
        path: RepoRelativePath::new(path.to_string()).map_err(RepoctlError::diagnostic)?,
        operation: "managed".to_string(),
        content: Some(content),
    })
}

fn block_operation(path: &str, content: &str) -> Result<FileOperation, RepoctlError> {
    Ok(FileOperation {
        path: RepoRelativePath::new(path.to_string()).map_err(RepoctlError::diagnostic)?,
        operation: "block".to_string(),
        content: Some(render_block(content)),
    })
}

fn apply_operations(
    root: &Utf8PathBuf,
    operations: &[FileOperation],
    dry_run: bool,
) -> Result<Vec<Diagnostic>, RepoctlError> {
    let mut diagnostics = Vec::new();
    if !dry_run {
        fs::create_dir_all(root.as_std_path())
            .map_err(|source| RepoctlError::io(root.clone(), source))?;
    }
    for operation in operations {
        let absolute = root.join(operation.path.as_str());
        if operation.operation == "directory" {
            if !dry_run {
                fs::create_dir_all(absolute.as_std_path())
                    .map_err(|source| RepoctlError::io(absolute.clone(), source))?;
            }
            continue;
        }
        let Some(content) = &operation.content else {
            continue;
        };
        let content_to_write = if absolute.exists() {
            let current = fs::read_to_string(absolute.as_std_path())
                .map_err(|source| RepoctlError::io(absolute.clone(), source))?;
            if current == *content {
                continue;
            }
            if !current.contains(MANAGED_HEADER)
                && !current.contains(LINE_COMMENT_MANAGED_HEADER)
                && !current.contains(BLOCK_BEGIN)
                && !is_repoctl_owned_skill_path(operation.path.as_str())
                && operation.operation != "block"
            {
                diagnostics.push(
                    Diagnostic::error(
                        "scaffold.conflict",
                        format!("refusing to overwrite unmanaged file `{}`", operation.path),
                    )
                    .with_path(operation.path.as_str()),
                );
                continue;
            }
            if operation.operation == "block" {
                replace_or_append_block(&current, content)
            } else {
                content.clone()
            }
        } else {
            content.clone()
        };
        if !dry_run {
            if let Some(parent) = absolute.parent() {
                fs::create_dir_all(parent.as_std_path())
                    .map_err(|source| RepoctlError::io(parent.to_path_buf(), source))?;
            }
            fs::write(absolute.as_std_path(), content_to_write)
                .map_err(|source| RepoctlError::io(absolute, source))?;
        }
    }
    if diagnostics
        .iter()
        .any(|diagnostic| diagnostic.severity == repoctl_core::Severity::Error)
    {
        return Err(RepoctlError::Diagnostics { diagnostics });
    }
    Ok(diagnostics)
}

fn is_repoctl_owned_skill_path(path: &str) -> bool {
    path.starts_with(".agents/skills/") || path.starts_with(".claude/skills/")
}

fn compact_line_diff(current: &str, expected: &str) -> String {
    let current_lines = current.lines().collect::<Vec<_>>();
    let expected_lines = expected.lines().collect::<Vec<_>>();
    let max_len = current_lines.len().max(expected_lines.len());
    let mut output = String::new();
    let mut shown = 0_usize;
    for index in 0..max_len {
        let current_line = current_lines.get(index).copied();
        let expected_line = expected_lines.get(index).copied();
        if current_line == expected_line {
            continue;
        }
        if shown >= 80 {
            output.push_str("... diff truncated ...\n");
            break;
        }
        if let Some(line) = current_line {
            output.push('-');
            output.push_str(line);
            output.push('\n');
        }
        if let Some(line) = expected_line {
            output.push('+');
            output.push_str(line);
            output.push('\n');
        }
        shown += 1;
    }
    output
}

