fn slug_from_path(path: &RepoRelativePath) -> Result<String, RepoctlError> {
    path.as_str()
        .rsplit('/')
        .next()
        .filter(|value| !value.is_empty())
        .map(ToString::to_string)
        .ok_or_else(|| {
            RepoctlError::diagnostic(Diagnostic::error(
                "new.path.invalid",
                "project path must include a final slug",
            ))
        })
}

fn project_name(path: &RepoRelativePath, kind: &ProjectKind) -> Result<String, RepoctlError> {
    let slug = slug_from_path(path)?;
    let prefix = match kind {
        ProjectKind::App => "apps",
        ProjectKind::Framework => "frameworks",
        ProjectKind::FoundationService => "foundations",
        ProjectKind::ProtoRoot | ProjectKind::CoreInfra => {
            return Err(RepoctlError::diagnostic(Diagnostic::error(
                "new.kind.unsupported",
                "unsupported project kind",
            )));
        }
    };
    Ok(format!("{prefix}.{slug}"))
}

fn owner_or_default(owner: Option<&OwnerHandle>, slug: &str) -> String {
    owner.map_or_else(|| format!("@{slug}"), ToString::to_string)
}

fn push_task<'a>(
    tasks: &mut BTreeMap<&'a str, Vec<String>>,
    task: &'a str,
    workspace: &str,
    command: &str,
) {
    tasks.entry(task).or_default().push(format!(
        "    - workspace: {workspace}\n      command: {command}"
    ));
}

fn render_tasks(tasks: &BTreeMap<&str, Vec<String>>) -> String {
    tasks
        .iter()
        .map(|(name, commands)| format!("  {name}:\n{}", commands.join("\n")))
        .collect::<Vec<_>>()
        .join("\n")
}

