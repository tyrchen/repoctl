    /// Plans and optionally applies repository initialization.
    pub fn init(&self, request: &InitRequest) -> Result<InitPlan, RepoctlError> {
        if request.layout != repoctl_core::RepoLayout::Functional {
            return Err(RepoctlError::diagnostic(Diagnostic::error(
                "init.layout.unsupported",
                "repoctl v0.2 only supports the functional layout",
            )));
        }
        let root = root_path(&request.repo_root)?;
        let mut operations = Vec::new();
        for directory in [
            ".repoctl",
            ".agent/skills",
            ".claude/skills",
            ".github/workflows",
            "protos",
            "apps",
            "foundations",
            "frameworks",
            "core-infra",
            "templates",
            "tools",
            "docs",
            "target/repoctl",
        ] {
            operations.push(directory_operation(directory)?);
        }
        operations.push(file_operation(
            "repo.yaml",
            repo_manifest(&request.name.to_string()),
        )?);
        operations.push(file_operation(
            "AGENTS.md",
            root_agents(&request.name.to_string()),
        )?);
        operations.push(file_operation("docs/index.md", docs_index())?);
        operations.extend(skill_operations()?);
        apply_operations(&root, &operations, request.dry_run)?;
        Ok(InitPlan {
            operations,
            warnings: Vec::new(),
            next_steps: vec![
                "Commit the initialized structure.".to_string(),
                "Create your first app with repoctl new app apps/<name>.".to_string(),
                "Run repoctl graph validate.".to_string(),
            ],
        })
    }

    /// Checks or syncs generated skills.
    pub fn skills(
        &self,
        request: &SkillsFacadeRequest,
    ) -> Result<SkillsFacadeReport, RepoctlError> {
        let root = locate_or_current(request.repo.as_deref())?;
        let operations = skill_operations()?;
        let mut diagnostics = Vec::new();
        for operation in &operations {
            let absolute = root.join(operation.path.as_str());
            match (&operation.content, absolute.exists()) {
                (Some(expected), true) => {
                    let current = fs::read_to_string(absolute.as_std_path())
                        .map_err(|source| RepoctlError::io(absolute.clone(), source))?;
                    if current != *expected {
                        diagnostics.push(
                            Diagnostic::error(
                                "skills.out_of_sync",
                                format!("skill `{}` is out of sync", operation.path),
                            )
                            .with_path(operation.path.as_str()),
                        );
                    }
                }
                (Some(_), false) => diagnostics.push(
                    Diagnostic::error(
                        "skills.missing",
                        format!("skill `{}` is missing", operation.path),
                    )
                    .with_path(operation.path.as_str()),
                ),
                (None, _) => {}
            }
        }
        if request.sync && !request.dry_run {
            apply_operations(&root, &operations, false)?;
            diagnostics.clear();
        }
        Ok(SkillsFacadeReport { diagnostics })
    }

    /// Plans and optionally applies a new project scaffold.
    pub fn new_project(&self, request: &NewProjectRequest) -> Result<RenderPlan, RepoctlError> {
        let root = locate_or_current(request.repo.as_deref())?;
        let operations = match request.kind {
            ProjectKind::App => Self::app_operations(request)?,
            ProjectKind::Framework => Self::framework_operations(request)?,
            ProjectKind::FoundationService => Self::foundation_operations(request)?,
            ProjectKind::ProtoRoot | ProjectKind::CoreInfra => {
                return Err(RepoctlError::diagnostic(Diagnostic::error(
                    "new.kind.unsupported",
                    "new project supports app, framework, and foundation-service",
                )));
            }
        };
        let diagnostics = apply_operations(&root, &operations, request.dry_run)?;
        Ok(RenderPlan {
            operations,
            diagnostics,
        })
    }

    /// Lists built-in and repository-local templates.
    pub fn list_templates(
        &self,
        request: &TemplateListRequest,
    ) -> Result<TemplateListReport, RepoctlError> {
        let root = locate_or_current(request.repo.as_deref())?;
        let repo_root = RepoRoot {
            absolute: root.clone(),
        };
        let source_resolver = DefaultTemplateSourceResolver::default();
        let mut templates = Vec::new();
        for name in builtin_template_names() {
            let template_data = source_resolver.resolve(
                &repo_root,
                &TemplateSource::Builtin {
                    name: name.to_string(),
                },
            )?;
            templates.push(TemplateSummary {
                source: format!("builtin:{name}"),
                name: template_data.manifest.name,
                kind: template_data.manifest.kind,
            });
        }
        let local_root = root.join("templates");
        if local_root.is_dir() {
            for entry in fs::read_dir(local_root.as_std_path())
                .map_err(|source| RepoctlError::io(local_root.clone(), source))?
            {
                let entry = entry.map_err(|source| RepoctlError::io(local_root.clone(), source))?;
                if !entry
                    .file_type()
                    .map_err(|source| RepoctlError::io(local_root.clone(), source))?
                    .is_dir()
                {
                    continue;
                }
                let name = entry.file_name().to_string_lossy().to_string();
                let source_root = RepoRelativePath::new(format!("templates/{name}"))
                    .map_err(RepoctlError::diagnostic)?;
                let template_data = source_resolver.resolve(
                    &repo_root,
                    &TemplateSource::Local {
                        root: source_root.clone(),
                    },
                );
                if let Ok(template_data) = template_data {
                    templates.push(TemplateSummary {
                        source: format!("local:{source_root}"),
                        name: template_data.manifest.name,
                        kind: template_data.manifest.kind,
                    });
                }
            }
        }
        templates.sort_by(|left, right| left.source.cmp(&right.source));
        Ok(TemplateListReport {
            templates,
            diagnostics: Vec::new(),
        })
    }

    /// Renders a built-in or local template into a plan-first file operation set.
    pub fn render_template(
        &self,
        request: &TemplateRenderRequest,
    ) -> Result<RenderPlan, RepoctlError> {
        let root = locate_or_current(request.repo.as_deref())?;
        let repo_root = RepoRoot {
            absolute: root.clone(),
        };
        let source_resolver = DefaultTemplateSourceResolver::default();
        let engine = MiniJinjaTemplateEngine;
        let template_data = source_resolver.resolve(&repo_root, &request.source)?;
        let mut operations = Vec::new();
        for file in &template_data.manifest.files {
            if !should_render(file.when.as_deref(), &request.inputs, &engine)? {
                continue;
            }
            let target = engine.render(&RenderRequest {
                template: template_data.manifest.clone(),
                file: file.clone(),
                context: request.inputs.clone(),
            })?;
            let target = String::from_utf8(target.bytes).map_err(|source| {
                RepoctlError::diagnostic(Diagnostic::error(
                    "template.target.invalid_utf8",
                    format!("template target did not render as UTF-8: {source}"),
                ))
            })?;
            let path = RepoRelativePath::new(target).map_err(RepoctlError::diagnostic)?;
            let source = template_source_content(&root, &request.source, &template_data, file)?;
            let existing = {
                let absolute = root.join(path.as_str());
                if absolute.is_file() {
                    Some(
                        fs::read_to_string(absolute.as_std_path())
                            .map_err(|source| RepoctlError::io(absolute, source))?,
                    )
                } else {
                    None
                }
            };
            let content =
                engine.render_content(file, &source, existing.as_deref(), &request.inputs)?;
            operations.push(FileOperation {
                path,
                operation: file.mode.clone(),
                content: Some(content),
            });
        }
        let diagnostics = apply_operations(&root, &operations, request.dry_run)?;
        Ok(RenderPlan {
            operations,
            diagnostics,
        })
    }

    fn app_operations(request: &NewProjectRequest) -> Result<Vec<FileOperation>, RepoctlError> {
        let slug = slug_from_path(&request.path)?;
        let project = project_name(&request.path, &ProjectKind::App)?;
        let owner = owner_or_default(request.owner.as_ref(), &slug);
        let mut workspaces = Vec::new();
        let mut tasks: BTreeMap<&str, Vec<String>> = BTreeMap::new();
        let stack = if request.stack.is_empty() {
            vec!["rust-api".to_string()]
        } else {
            request.stack.clone()
        };
        if stack.iter().any(|entry| entry == "rust-api") {
            workspaces.push(
                r#"  - name: api
    language: rust
    root: api
    manifest: api/Cargo.toml
    lockfile: api/Cargo.lock
    target_dir: "{repo_root}/target/rust""#
                    .to_string(),
            );
            push_task(&mut tasks, "check", "api", "cargo check --workspace");
            push_task(&mut tasks, "test", "api", "cargo test --workspace");
            push_task(
                &mut tasks,
                "build",
                "api",
                "cargo build --workspace --release",
            );
        }
        if stack.iter().any(|entry| entry == "bun-web") {
            workspaces.push(
                r#"  - name: web
    language: typescript
    toolchain: bun
    root: web
    manifest: web/package.json
    lockfile: web/bun.lock
    cache_dir: "{repo_root}/target/bun""#
                    .to_string(),
            );
            push_task(&mut tasks, "check", "web", "bun run check");
            push_task(&mut tasks, "test", "web", "bun test");
            push_task(&mut tasks, "build", "web", "bun run build");
        }
        if stack.iter().any(|entry| entry == "uv-jobs") {
            workspaces.push(
                r#"  - name: jobs
    language: python
    toolchain: uv
    root: jobs
    manifest: jobs/pyproject.toml
    lockfile: jobs/uv.lock
    cache_dir: "{repo_root}/target/uv""#
                    .to_string(),
            );
            push_task(&mut tasks, "check", "jobs", "uv run ruff check .");
            push_task(&mut tasks, "test", "jobs", "uv run pytest");
        }
        let mut manifest = format!(
            r#"{MANAGED_HEADER}
schema: company.project/v1
name: {project}
kind: app
path: {path}
owners:
  - "{owner}"
visibility: internal

workspaces:
{workspaces}

tasks:
{tasks}
"#,
            path = request.path,
            workspaces = workspaces.join("\n"),
            tasks = render_tasks(&tasks),
        );
        if let Some(provider) = &request.iac {
            write!(
                manifest,
                r"
iac:
  root: iac
  provider: {}
  stacks:
    - dev
    - staging
    - prod
",
                iac_provider_name(provider)
            )
            .map_err(|error| {
                RepoctlError::Internal(format!("failed to render iac block: {error}"))
            })?;
        }
        manifest.push_str(
            r#"
deploy:
  root: deploy
  environments:
    - dev
    - staging
    - prod

ai:
  editable:
    - api/**
    - web/src/**
    - jobs/**
    - iac/**
    - deploy/**
    - docs/**
  do_not_edit:
    - "**/generated/**"
    - deploy/prod/**
    - iac/stacks/prod/**
  docs:
    - README.md
"#,
        );
        let mut operations = project_base_operations(request, &slug, manifest)?;
        if stack.iter().any(|entry| entry == "rust-api") {
            operations.push(file_operation(
                &format!("{}/api/Cargo.toml", request.path),
                rust_workspace_toml(&slug),
            )?);
            operations.push(file_operation(
                &format!("{}/api/src/lib.rs", request.path),
                "//! App API crate.\n".to_string(),
            )?);
        }
        if stack.iter().any(|entry| entry == "bun-web") {
            operations.push(file_operation(
                &format!("{}/web/package.json", request.path),
                package_json(&slug),
            )?);
            operations.push(file_operation(
                &format!("{}/web/src/main.tsx", request.path),
                "export const appName = \"repoctl-app\";\n".to_string(),
            )?);
        }
        if stack.iter().any(|entry| entry == "uv-jobs") {
            operations.push(file_operation(
                &format!("{}/jobs/pyproject.toml", request.path),
                pyproject_toml(&slug),
            )?);
            operations.push(file_operation(
                &format!("{}/jobs/src/main.py", request.path),
                "def main() -> None:\n    return None\n".to_string(),
            )?);
        }
        if request.iac.is_some() {
            operations.push(file_operation(
                &format!("{}/iac/Pulumi.yaml", request.path),
                format!("{MANAGED_HEADER}\nname: {slug}\nruntime: yaml\n"),
            )?);
            operations.push(file_operation(
                &format!("{}/iac/stacks/prod.yaml", request.path),
                format!("{MANAGED_HEADER}\nconfig: {{}}\n"),
            )?);
        }
        Ok(operations)
    }

    fn framework_operations(
        request: &NewProjectRequest,
    ) -> Result<Vec<FileOperation>, RepoctlError> {
        let slug = slug_from_path(&request.path)?;
        let project = project_name(&request.path, &ProjectKind::Framework)?;
        let owner = owner_or_default(request.owner.as_ref(), "platform");
        let languages = if request.languages.is_empty() {
            vec!["rust".to_string()]
        } else {
            request.languages.clone()
        };
        let mut workspaces = Vec::new();
        let mut public_facades = String::new();
        let mut internal = String::new();
        let mut tasks: BTreeMap<&str, Vec<String>> = BTreeMap::new();
        if languages.iter().any(|language| language == "rust") {
            workspaces.push(
                r#"  - name: rust
    language: rust
    root: rust
    manifest: rust/Cargo.toml
    lockfile: rust/Cargo.lock
    target_dir: "{repo_root}/target/rust""#
                    .to_string(),
            );
            writeln!(public_facades, "  rust:\n    - rust/crates/{slug}-facade").map_err(
                |error| RepoctlError::Internal(format!("failed to render facade map: {error}")),
            )?;
            writeln!(internal, "  rust:\n    - rust/crates/{slug}-internal").map_err(|error| {
                RepoctlError::Internal(format!("failed to render internal map: {error}"))
            })?;
            push_task(&mut tasks, "check", "rust", "cargo check --workspace");
            push_task(&mut tasks, "test", "rust", "cargo test --workspace");
        }
        if languages.iter().any(|language| language == "typescript") {
            workspaces.push(
                r#"  - name: ts
    language: typescript
    toolchain: bun
    root: ts
    manifest: ts/package.json
    lockfile: ts/bun.lock
    cache_dir: "{repo_root}/target/bun""#
                    .to_string(),
            );
            writeln!(public_facades, "  typescript:\n    - ts/packages/{slug}").map_err(
                |error| RepoctlError::Internal(format!("failed to render facade map: {error}")),
            )?;
            writeln!(internal, "  typescript:\n    - ts/packages/{slug}-internal").map_err(
                |error| RepoctlError::Internal(format!("failed to render internal map: {error}")),
            )?;
            push_task(&mut tasks, "check", "ts", "bun run check");
            push_task(&mut tasks, "test", "ts", "bun test");
        }
        let manifest = format!(
            r#"{MANAGED_HEADER}
schema: company.project/v1
name: {project}
kind: framework
path: {path}
owners:
  - "{owner}"

workspaces:
{workspaces}

public_facades:
{public_facades}
internal:
{internal}
tasks:
{tasks}

policies:
  allow_app_dependency_on_facade_only: true
"#,
            path = request.path,
            workspaces = workspaces.join("\n"),
            tasks = render_tasks(&tasks),
        );
        let mut operations = project_base_operations(request, &slug, manifest)?;
        if languages.iter().any(|language| language == "rust") {
            operations.push(file_operation(
                &format!("{}/rust/Cargo.toml", request.path),
                rust_workspace_manifest_toml(&[
                    format!("crates/{slug}-facade"),
                    format!("crates/{slug}-internal"),
                ]),
            )?);
            operations.push(file_operation(
                &format!("{}/rust/crates/{slug}-facade/Cargo.toml", request.path),
                rust_workspace_toml(&format!("{slug}-facade")),
            )?);
            operations.push(file_operation(
                &format!("{}/rust/crates/{slug}-internal/Cargo.toml", request.path),
                rust_workspace_toml(&format!("{slug}-internal")),
            )?);
            operations.push(file_operation(
                &format!("{}/rust/crates/{slug}-facade/src/lib.rs", request.path),
                "//! Public facade crate.\n".to_string(),
            )?);
            operations.push(file_operation(
                &format!("{}/rust/crates/{slug}-internal/src/lib.rs", request.path),
                "//! Internal crate.\n".to_string(),
            )?);
        }
        if languages.iter().any(|language| language == "typescript") {
            operations.push(file_operation(
                &format!("{}/ts/package.json", request.path),
                package_json(&slug),
            )?);
        }
        Ok(operations)
    }

