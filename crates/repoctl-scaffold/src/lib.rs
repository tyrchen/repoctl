fn iac_operations(
    project_path: &str,
    slug: &str,
    provider: &IacProvider,
) -> Result<Vec<FileOperation>, RepoctlError> {
    let mut operations = Vec::new();
    match provider {
        IacProvider::Pulumi => {
            operations.push(file_operation(
                &format!("{project_path}/iac/Pulumi.yaml"),
                pulumi_yaml(slug),
            )?);
            for stack in ["dev", "staging", "prod"] {
                operations.push(file_operation(
                    &format!("{project_path}/iac/stacks/{stack}.yaml"),
                    pulumi_stack_yaml(slug, stack),
                )?);
            }
        }
        IacProvider::Terraform => {
            operations.push(file_operation(
                &format!("{project_path}/iac/main.tf"),
                terraform_main_tf(slug, "terraform"),
            )?);
            for env in ["dev", "staging", "prod"] {
                operations.push(file_operation(
                    &format!("{project_path}/iac/env/{env}.tfvars"),
                    terraform_tfvars(slug, env),
                )?);
            }
        }
        IacProvider::OpenTofu => {
            operations.push(file_operation(
                &format!("{project_path}/iac/main.tf"),
                terraform_main_tf(slug, "opentofu"),
            )?);
            for env in ["dev", "staging", "prod"] {
                operations.push(file_operation(
                    &format!("{project_path}/iac/env/{env}.tfvars"),
                    terraform_tfvars(slug, env),
                )?);
            }
        }
    }
    Ok(operations)
}

fn terraform_main_tf(slug: &str, provider: &str) -> String {
    format!(
        r#"{MANAGED_HEADER}
terraform {{
  required_version = ">= 1.8.0"
}}

variable "project" {{
  type    = string
  default = "{slug}"
}}

variable "environment" {{
  type = string
}}

locals {{
  repoctl_provider = "{provider}"
  project          = var.project
  environment      = var.environment
}}
"#
    )
}

