//! Standalone, executable GitHub Actions workflows with an explicit required gate.

use repoctl_core::RepoSnapshot;

pub(super) fn render_github_actions_workflow(_snapshot: &RepoSnapshot) -> String {
    WORKFLOW.replace("@VERSION@", env!("CARGO_PKG_VERSION"))
}

const WORKFLOW: &str = r#"# Generated by repoctl. Refresh with: repoctl ci workflow --write
name: repoctl
on:
  pull_request:
  push:
    branches: [main, master]
permissions:
  contents: read
jobs:
  graph:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    outputs:
      matrix: ${{ steps.matrix.outputs.matrix }}
      has_tasks: ${{ steps.matrix.outputs.has_tasks }}
    steps:
      - uses: actions/checkout@v7
        with:
          fetch-depth: 0
      - uses: dtolnay/rust-toolchain@stable
      - name: Install repoctl
        run: cargo install repoctl-cli --version '=@VERSION@' --locked
      - name: Validate offline graph
        run: repoctl graph validate --mode metadata
      - id: matrix
        name: Select affected tasks
        env:
          BASE: ${{ github.event.pull_request.base.sha || github.event.before }}
          HEAD: ${{ github.sha }}
        run: |
          if [ -n "$BASE" ] && git rev-parse --verify --end-of-options "$BASE^{commit}" >/dev/null 2>&1; then
            repoctl inspect size --scope changed --base "$BASE" --head "$HEAD" --fail-on error
            matrix=$(repoctl ci matrix --base "$BASE" --head "$HEAD" --tasks check,test,build --format github-actions)
          else
            repoctl inspect size --scope all --fail-on error
            matrix=$(repoctl ci matrix --tasks check,test,build --fallback all --format github-actions)
          fi
          echo "matrix=$matrix" >> "$GITHUB_OUTPUT"
          MATRIX="$matrix" python3 -c 'import json,os; print("has_tasks=" + str(bool(json.loads(os.environ["MATRIX"])["include"])).lower())' >> "$GITHUB_OUTPUT"
  tasks:
    needs: graph
    if: needs.graph.outputs.has_tasks == 'true'
    runs-on: ubuntu-latest
    timeout-minutes: 60
    strategy:
      fail-fast: false
      matrix: ${{ fromJson(needs.graph.outputs.matrix) }}
    name: ${{ matrix.project }}:${{ matrix.workspace }}:${{ matrix.task }}
    steps:
      - uses: actions/checkout@v7
        with:
          fetch-depth: 0
      - uses: dtolnay/rust-toolchain@stable
      - name: Install repoctl
        run: cargo install repoctl-cli --version '=@VERSION@' --locked
      - uses: actions/setup-node@v7
        if: matrix.needsNode
        with:
          node-version: 'lts/*'
      - name: Enable Node package managers
        if: matrix.needsNode
        run: npm install --global corepack && corepack enable
      - uses: oven-sh/setup-bun@v2
        if: matrix.needsBun
      - uses: astral-sh/setup-uv@v10
        if: matrix.needsPython
      - name: Install protobuf compiler
        if: matrix.needsProtoc
        run: sudo apt-get update && sudo apt-get install -y protobuf-compiler
      - uses: bufbuild/buf-action@v1
        if: matrix.needsBuf
        with:
          version: '1.73.0'
          setup_only: true
      - name: Install dependencies and run task with prerequisites
        env:
          PROJECT: ${{ matrix.project }}
          WORKSPACE: ${{ matrix.workspace }}
          TASK: ${{ matrix.task }}
        run: repoctl ci run-step --project "$PROJECT" --workspace "$WORKSPACE" --task "$TASK" --install
  required:
    name: repoctl required
    runs-on: ubuntu-latest
    timeout-minutes: 5
    needs: [graph, tasks]
    if: always()
    steps:
      - name: Require successful verification
        env:
          GRAPH: ${{ needs.graph.result }}
          TASKS: ${{ needs.tasks.result }}
          HAS_TASKS: ${{ needs.graph.outputs.has_tasks }}
        run: |
          test "$GRAPH" = success
          if [ "$HAS_TASKS" = true ]; then
            test "$TASKS" = success
          else
            test "$TASKS" = skipped
          fi
"#;
